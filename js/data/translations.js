export function getGlobalLanguage() {
  return localStorage.getItem('orca_chat_lang') || localStorage.getItem('orca_fisherman_lang') || 'en';
}

export function setGlobalLanguage(lang) {
  if (['en', 'hi', 'mr'].includes(lang)) {
    localStorage.setItem('orca_chat_lang', lang);
    localStorage.setItem('orca_fisherman_lang', lang);
  }
}

export function t(key, lang) {
  const activeLang = lang || getGlobalLanguage();
  const dict = translations[activeLang] || translations.en;
  return dict[key] || translations.en[key] || key;
}
